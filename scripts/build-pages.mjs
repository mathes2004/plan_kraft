import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const stage = join(root, '.pages-preview');
const marker = join(stage, '.plan-kraft-static-preview');
const repository = process.env.GITHUB_REPOSITORY || 'mathes2004/plan_kraft';
const [owner, repo, ...extra] = repository.split('/');
if (!owner || !repo || extra.length || !/^[\w.-]+$/.test(owner) || !/^[\w.-]+$/.test(repo)) {
  throw new Error('GITHUB_REPOSITORY must be an owner/repository name.');
}
const defaultPath = repo.toLowerCase() === `${owner.toLowerCase()}.github.io` ? '' : `/${repo}`;
const basePath = process.env.PAGES_BASE_PATH ?? defaultPath;
if (basePath && !/^\/[\w.-]+$/.test(basePath)) throw new Error('Invalid Pages base path.');
const origin = new URL(process.env.PAGES_SITE_ORIGIN || `https://${owner.toLowerCase()}.github.io`)
  .origin;

// Clean only the dedicated staging directory previously created by this script.
if (dirname(stage) !== root) throw new Error('Preview staging directory is outside the project.');
if (existsSync(stage)) {
  if (!existsSync(marker))
    throw new Error('Refusing to replace an unrecognized preview directory.');
  rmSync(stage, { recursive: true, force: true });
}
mkdirSync(stage);
writeFileSync(marker, 'Generated by scripts/build-pages.mjs\n');
for (const file of ['package.json', 'package-lock.json', 'tsconfig.json', 'next.config.ts']) {
  cpSync(join(root, file), join(stage, file));
}
cpSync(join(root, 'public'), join(stage, 'public'), { recursive: true });
cpSync(join(root, 'src'), join(stage, 'src'), {
  recursive: true,
  filter(source) {
    const path = relative(join(root, 'src'), source).replaceAll('\\', '/');
    return !['app/api', 'lib/server'].some(
      (excluded) => path === excluded || path.startsWith(`${excluded}/`),
    );
  },
});

const build = spawnSync(
  process.execPath,
  [join(root, 'node_modules/next/dist/bin/next'), 'build', stage],
  {
    cwd: root,
    stdio: 'inherit',
    env: {
      ...process.env,
      NEXT_PUBLIC_STATIC_PREVIEW: 'true',
      NEXT_PUBLIC_BASE_PATH: basePath,
      NEXT_PUBLIC_SITE_URL: origin,
      NEXT_PUBLIC_TURNSTILE_SITE_KEY: '',
      SITE_INDEXABLE: 'false',
      PAGES_WORKSPACE_ROOT: root,
    },
  },
);
if (build.error) throw build.error;
if (build.status !== 0) process.exit(build.status || 1);
if (!existsSync(join(stage, 'out/index.html')))
  throw new Error('Static homepage was not exported.');
// Exported segment payloads can be nested on disk, while the router requests dotted names.
// Materialize those aliases so static hosts can serve them without rewrite rules.
const output = join(stage, 'out');
function addSegmentAliases(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const file = join(directory, entry.name);
    if (entry.isDirectory()) addSegmentAliases(file);
    else if (entry.name.endsWith('.txt')) {
      const segments = relative(output, file).split(/[\\/]/);
      const segmentStart = segments.findIndex((part) => part.startsWith('__next.'));
      if (segmentStart < 0 || segmentStart === segments.length - 1) continue;
      const alias = join(
        output,
        ...segments.slice(0, segmentStart),
        segments.slice(segmentStart).join('.'),
      );
      if (!existsSync(alias)) cpSync(file, alias);
    }
  }
}
addSegmentAliases(output);
writeFileSync(join(stage, 'out/.nojekyll'), '');
console.log(`\nStatic client preview ready: ${join(stage, 'out')}`);
console.log(`Publish location: ${origin}${basePath}/ (not yet deployed)`);
